def glyph_width(rows):
    return max((len(r) for r in rows), default=0)


def text_size(text, font, spacing, space):
    w = 0
    for i, ch in enumerate(text):
        w += space if ch == ' ' else glyph_width(font[ch])
        if i < len(text) - 1:
            w += spacing
    h = max(len(font[ch]) for ch in text if ch != ' ')
    return w, h


def draw_text(layer, text, x, y, color, font=SMALL, spacing=1, space=3, bold=False):
    cx = x
    for ch in text:
        if ch == ' ':
            cx += space + spacing
            continue
        rows = font[ch]
        for gy, row in enumerate(rows):
            for gx, c in enumerate(row):
                if c == '#':
                    layer.px(cx + gx, y + gy, color)
                    if bold:
                        layer.px(cx + gx + 1, y + gy, color)
        cx += glyph_width(rows) + (1 if bold else 0) + spacing
    return cx - spacing


def text_width(text, font=SMALL, spacing=1, space=3, bold=False):
    w = 0
    for i, ch in enumerate(text):
        w += (space if ch == ' ' else glyph_width(font[ch]) + (1 if bold else 0))
        if i < len(text) - 1:
            w += spacing
    return w


def wordmark(face, edge, shade=None, spacing=2):
    """'Almighty' in DISPLAY: face colour, 1-px edge outline, optional 1-px lower shade inside stems."""
    text = 'Almighty'
    w = text_width(text, DISPLAY, spacing) + 2
    L = Layer(w, 22)
    draw_text(L, text, 1, 1, face, DISPLAY, spacing)
    if shade:
        # Bottom row of every horizontal run and right column of every stem gets the shade: a hard bevel.
        src = L.im.copy()
        for y in range(L.h):
            for x in range(L.w):
                if src.getpixel((x, y))[3] and not src.getpixel((x, min(y + 1, L.h - 1)))[3]:
                    L.px(x, y, shade)
    L.outline(edge, diag=True)
    return L
